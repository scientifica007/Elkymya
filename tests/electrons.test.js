'use strict';
const assert=require('node:assert/strict');
const {inspectElectrons,analyze,inspectStructure,MOLECULES}=require('../src/engine.js');
let n=0;
const check=(cond,msg)=>{assert.ok(cond,msg);n++};
const editor=(symbols,edges,charges={},radicals={})=>{
 const atoms=symbols.map((symbol,i)=>({id:'a'+i,symbol,...(Object.hasOwn(charges,i)?{formalCharge:charges[i]}:{}),...(Object.hasOwn(radicals,i)?{unpairedElectrons:radicals[i]}:{})}));
 return {atoms,bonds:edges.map(([a,b,order])=>({a:'a'+a,b:'a'+b,order}))};
};
let w=editor(['O','H','H'],[[0,1,1],[0,2,1]],{0:0,1:0,2:0},{0:0,1:0,2:0});
let e=inspectElectrons(w.atoms,w.bonds);
check(e.complete&&e.netCharge===0,'water explicit neutral state');
check(e.entries[0].lonePairs===2,'water oxygen lone pairs');
check(e.entries[1].lonePairs===0,'hydrogen no lone pairs');
check(analyze(w.atoms,w.bonds).kind==='found','water stays discoverable');
const unknown=editor(['O','H'],[[0,1,1]]);
check(inspectElectrons(unknown.atoms,unknown.bonds).status==='unassigned','unset is distinct from zero');
const partial=editor(['O','H'],[[0,1,1]],{0:0},{0:1});
check(inspectElectrons(partial.atoms,partial.bonds).status==='partial','partial electron assignment');
const radical=editor(['O','H'],[[0,1,1]],{0:0,1:0},{0:1,1:0});
e=inspectElectrons(radical.atoms,radical.bonds);
check(e.complete&&e.totalRadicals===1,'OH radical explicitly recorded');
check(e.entries[0].lonePairs===2,'OH radical oxygen two lone pairs');
const anion=editor(['O','H'],[[0,1,1]],{0:-1,1:0},{0:0,1:0});
e=inspectElectrons(anion.atoms,anion.bonds);
check(e.complete&&e.netCharge===-1,'hydroxide anion');
check(e.entries[0].lonePairs===3,'hydroxide three lone pairs');
const ammonium=editor(['N','H','H','H','H'],[[0,1,1],[0,2,1],[0,3,1],[0,4,1]],{0:1,1:0,2:0,3:0,4:0},{0:0,1:0,2:0,3:0,4:0});
e=inspectElectrons(ammonium.atoms,ammonium.bonds);
check(e.complete&&e.netCharge===1,'ammonium charge and electron accounting');
check(e.entries[0].lonePairs===0,'ammonium nitrogen zero lone pairs');
check(analyze(ammonium.atoms,ammonium.bonds).kind==='unknown','ammonium must not be dismissed as overbonded nor invented as curated');
const badWater=editor(['O','H','H'],[[0,1,1],[0,2,1]],{0:1,1:0,2:0},{0:0,1:0,2:0});
check(inspectElectrons(badWater.atoms,badWater.bonds).invalid,'invalid charge parity flagged');
check(analyze(badWater.atoms,badWater.bonds).kind==='electronic-variant','known skeleton with invalid electron state must not be discovered');
const chargedWater=editor(['O','H','H'],[[0,1,1],[0,2,1]],{0:0,1:0,2:1},{0:0,1:0,2:0});
check(analyze(chargedWater.atoms,chargedWater.bonds).kind==='electronic-variant','charged known connectivity not automatically same neutral molecule');
const ozone=MOLECULES.find(x=>x.id==='ozone');
check(ozone.caution.includes('الرنين'),'ozone remains resonance-cautioned');
const screenshot=editor(['H','O','C','O','O','O','O'],[[0,1,1],[1,2,1],[2,3,1],[2,4,1],[4,5,1],[5,6,1]]);
const report=inspectStructure(screenshot.atoms,screenshot.bonds);
check(report.formula==='CHO₅' && report.electronic.status==='unassigned','CHO5 diagnostics preserved');
const unchanged=editor(['H','H'],[[0,1,1]]);
check(analyze(unchanged.atoms,unchanged.bonds).kind==='found','legacy structures still discoverable');
console.log('PASS: '+n+' electron-model assertions');
